export function t(key, lang = 'uz', params = {}) {
  const l = translations[lang] ? lang : 'uz'
  const value = translations[l][key] ?? translations['uz'][key] ?? key
  // simple templating
  return value.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, p) => params[p] ?? '')
}

export function getStoredLang() {
  try { const v = localStorage.getItem('uyda_lang'); if (v && (v==='uz' || v==='ru' || v==='en')) return v } catch(e) {}
  return 'uz'
}
